import { Link } from 'react-router'
import { LANGUAGES } from '../../shared/languages'
import { card, muted, Screen } from '../components/ui'

const REPO_LICENSE_URL = 'https://www.apache.org/licenses/LICENSE-2.0'
const external = { target: '_blank', rel: 'noopener noreferrer' } as const
const linkClass = 'underline underline-offset-2'

/** Credits: the bundled word lists (attribution required by their licences), the app licence, AI content. */
export function About() {
  const lists = Object.values(LANGUAGES).filter((l) => l.wordlist)
  return (
    <Screen
      title="About"
      action={
        <Link to="/settings" className="-mr-2 inline-flex min-h-11 items-center px-2 text-sm font-medium text-zinc-500 underline dark:text-zinc-400">
          Settings
        </Link>
      }
    >
      <section className={`${card} flex flex-col gap-2`}>
        <h2 className="font-semibold">Flashcards</h2>
        <p className="text-sm">
          A spaced-repetition vocabulary app. The app's source code is released under the{' '}
          <a className={linkClass} href={REPO_LICENSE_URL} {...external}>
            Apache License 2.0
          </a>
          .
        </p>
        <p className="text-sm">
          Translations and example sentences are generated by AI and can contain mistakes. You can correct any word from its page in Words.
        </p>
      </section>

      <section className={`${card} flex flex-col gap-3`}>
        <h2 className="font-semibold">Word lists</h2>
        {lists.length === 0 && <p className={muted}>No bundled word lists.</p>}
        {lists.map((l) => (
          <div key={l.code} className="flex flex-col gap-1" data-testid={`wordlist-${l.code}`}>
            <h3 className="text-sm font-medium">{l.name}</h3>
            <p className="text-sm">
              <a className={linkClass} href={l.wordlist!.url} {...external}>
                {l.wordlist!.name}
              </a>{' '}
              ·{' '}
              <a className={linkClass} href={l.wordlist!.licenseUrl} {...external}>
                {l.wordlist!.license}
              </a>
            </p>
            <p className={muted}>{l.wordlist!.attribution}</p>
          </div>
        ))}
      </section>
    </Screen>
  )
}
