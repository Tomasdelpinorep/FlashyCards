/**
 * Generate the D1 migration for a bundled word list (PLAN.md section 5, M7).
 *
 *   npm run wordlist:sql                 # data/wordlists/de.json -> migrations/0002_wordlist_de.sql
 *   npm run wordlist:sql -- es 0003      # data/wordlists/es.json -> migrations/0003_wordlist_es.sql
 *
 * lemma_key is computed with the app's own termKey() (src/shared/normalize.ts), so /suggest
 * compares exactly the keys cards use. The script refuses a list whose lemma keys are not unique,
 * whose ranks are not 1..N, or whose POS is not one of ai/schema.ts POS_VALUES.
 *
 * Migrations run through wrangler, not a Worker request, so the per-request statement budget does
 * not apply; rows still go in multi-row INSERTs of ROWS_PER_INSERT rows (literal values, no bound
 * parameters, each statement a few KB, far below D1's 100 KB statement limit).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { isLanguageCode } from '../src/shared/languages'
import { termKey } from '../src/shared/normalize'
import { POS_VALUES } from '../src/worker/ai/schema'

const ROWS_PER_INSERT = 100
const root = join(dirname(fileURLToPath(import.meta.url)), '..')

export type WordlistFile = {
  source: string
  license: string
  attribution: string
  items: { rank: number; lemma: string; pos: string; gender?: string }[]
}

const sqlString = (s: string) => `'${s.replace(/'/g, "''")}'`

export function wordlistToSql(lang: string, list: WordlistFile): string {
  if (!isLanguageCode(lang)) throw new Error(`Unknown language "${lang}"`)
  const keys = new Map<string, number>()
  list.items.forEach((it, i) => {
    if (it.rank !== i + 1) throw new Error(`rank ${it.rank} at position ${i + 1}: ranks must be 1..N in order`)
    if (!(POS_VALUES as readonly string[]).includes(it.pos)) throw new Error(`rank ${it.rank}: invalid pos "${it.pos}"`)
    const key = termKey(lang, it.lemma)
    if (!key) throw new Error(`rank ${it.rank}: empty lemma`)
    const dup = keys.get(key)
    if (dup !== undefined) throw new Error(`rank ${it.rank} "${it.lemma}": lemma key "${key}" already used by rank ${dup}`)
    keys.set(key, it.rank)
  })

  const out = [
    `-- Generated by scripts/wordlist-to-sql.ts from data/wordlists/${lang}.json. Do not edit by hand.`,
    `-- Source: ${list.source}`,
    `-- License: ${list.license}. ${list.attribution}`,
    `-- ${list.items.length} lemmas.`,
    `DELETE FROM wordlist WHERE lang = ${sqlString(lang)};`,
  ]
  for (let i = 0; i < list.items.length; i += ROWS_PER_INSERT) {
    const values = list.items
      .slice(i, i + ROWS_PER_INSERT)
      .map((it) => `(${sqlString(lang)}, ${it.rank}, ${sqlString(it.lemma)}, ${sqlString(termKey(lang, it.lemma))}, ${sqlString(it.pos)})`)
    out.push(`INSERT INTO wordlist (lang, rank, lemma, lemma_key, pos) VALUES\n${values.join(',\n')};`)
  }
  return out.join('\n') + '\n'
}

function main() {
  const [lang = 'de', number = '0002'] = process.argv.slice(2)
  const list = JSON.parse(readFileSync(join(root, 'data', 'wordlists', `${lang}.json`), 'utf8')) as WordlistFile
  const file = join(root, 'migrations', `${number}_wordlist_${lang}.sql`)
  writeFileSync(file, wordlistToSql(lang, list))
  console.log(`${list.items.length} lemmas -> ${file}`)
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main()
